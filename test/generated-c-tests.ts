import {LanguageKey} from '../types/languages.interfaces.js';
import {makeCompilationEnvironment, makeFakeCompilerInfo, makeFakeParseFiltersAndOutputOptions} from './utils.js';

// The fixtures are the raw output of valac 0.56.6, mrustc (master) and pythran 0.15 on godbolt.org for a function
// that switches on an int, with a default case. Likewise the C# that ILSpy (trunk) decompiles from a switch, the
// C++ that llvm-tblgen (trunk) generates from the searchable_tables example, and the C that TileLang 0.1.14 generates
// from its default example. Spatch is not installed on godbolt.org, so the Coccinelle fixtures are the output of
// spatch 1.1.1 (Ubuntu 24.04) for a patch on the same switch.
const fixture = (name: string) => fs.readFileSync(`./test/generated-c/${name}`, 'utf8');

// the filters the site turns on by default
const defaultFilters = makeFakeParseFiltersAndOutputOptions({
    labels: true,
    directives: true,
    commentOnly: true,
    libraryCode: true,
    demangle: true,
    intel: true,
});

function makeCompiler<T>(ctor: new (...args: any[]) => T, lang: string): T {
    const ce = makeCompilationEnvironment({languages: {[lang]: {id: lang as LanguageKey}}});
    return new ctor(makeFakeCompilerInfo({exe: '/dev/null', lang: lang as LanguageKey}), ce);
}

const texts = (asm: ParsedAsmResultLine[]) => asm.map(line => line.text);

describe('Vala generated C', () => {
    let vala: ValaCompiler;
    const output = fixture('vala-switch.c');

    beforeAll(() => {
        vala = makeCompiler(ValaCompiler, 'vala');
    });

    it('keeps the C intact with the default filters', async () => {
        const lines = texts((await vala.processAsm({asm: output}, defaultFilters, [])).asm);
        expect(lines).toContain('/* example.c generated by valac 0.56.6, the Vala compiler');
        expect(lines).toContain('#include <glib.h>');
        expect(lines).toContain('#if !defined(VALA_EXTERN)');
        expect(lines).toContain('                default:');
    });

    it('hides #line with the directives filter', async () => {
        const lines = texts((await vala.processAsm({asm: output}, defaultFilters, [])).asm);
        expect(lines.filter(line => line.includes('#line'))).toEqual([]);
        const unfiltered = makeFakeParseFiltersAndOutputOptions({});
        const all = texts((await vala.processAsm({asm: output}, unfiltered, [])).asm);
        expect(all.filter(line => line.includes('#line')).length).toBeGreaterThan(0);
    });

    it('maps lines to the source using #line', async () => {
        const asm = (await vala.processAsm({asm: output}, defaultFilters, [])).asm;
        const sourceOf = (text: string) => asm.find(line => line.text.trim() === text)?.source;
        expect(sourceOf('result = 20;')).toEqual({file: '/app/example.vala', line: 6});
        expect(sourceOf('g_print ("%d\\n", classify (2));')).toEqual({file: '/app/example.vala', line: 13});
        expect(sourceOf('#include <glib.h>')).toBeNull();
    });

    it('leaves the binary output to the asm parser', async () => {
        const process = vi.spyOn(vala.generatedCodeParser, 'process');
        await vala.processAsm(
            {asm: 'classify:\n        ret'},
            makeFakeParseFiltersAndOutputOptions({binary: true}),
            [],
        );
        expect(process).not.toHaveBeenCalled();
        process.mockRestore();
    });
});

